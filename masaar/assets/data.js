// Automatic gap detector — called by the agent and by the Security tab.
export function detectGaps(runtime) {
  const gaps = [];
  const isHttps = runtime.protocol === 'https:' || runtime.host === 'localhost';
  if (!isHttps) gaps.push({ id:'g1', severity:'high',
    title_en:'App is not served over HTTPS', title_ar:'التطبيق يعمل بدون HTTPS',
    fix_en:'Deploy behind Vercel HTTPS or a TLS-terminating proxy.',
    fix_ar:'انشر التطبيق خلف Vercel أو خادم يُنهي شهادة TLS.' });

  if (!runtime.serviceWorker) gaps.push({ id:'g2', severity:'medium',
    title_en:'Service worker not registered', title_ar:'لم يُسجَّل الـ service worker',
    fix_en:'Register /sw.js; enables offline and integrity boundary.',
    fix_ar:'سجّل /sw.js لتفعيل العمل بدون إنترنت وحدود التحقق.' });

  if (runtime.hasApiKeys && !runtime.hasMaskUI) gaps.push({ id:'g3', severity:'medium',
    title_en:'Provider keys not masked in UI', title_ar:'مفاتيح المزوّد ظاهرة في الواجهة',
    fix_en:'Show only the last 4 characters; hide by default.',
    fix_ar:'أظهر آخر أربعة أحرف فقط، وأخفِ المفتاح افتراضيًا.' });

  if (!runtime.csp) gaps.push({ id:'g4', severity:'high',
    title_en:'No Content-Security-Policy detected', title_ar:'لا توجد سياسة أمن محتوى',
    fix_en:'Add CSP with connect-src pinned to trusted LLM hosts.',
    fix_ar:'أضف CSP تحصر الاتصال بالمزوّدين الموثوقين.' });

  if (runtime.thirdPartyScripts?.length) gaps.push({ id:'g5', severity:'medium',
    title_en:'Third-party scripts loaded', title_ar:'ملفات برمجية من طرف ثالث محمَّلة',
    detail: runtime.thirdPartyScripts.join(', '),
    fix_en:'Self-host or remove; every third party expands the attack surface.',
    fix_ar:'استضف الملفات محلّيًا أو أزلها، فكل طرف ثالث يوسّع سطح الهجوم.' });

  if (!runtime.auditLog) gaps.push({ id:'g6', severity:'low',
    title_en:'Audit log not enabled', title_ar:'سجل التدقيق غير مفعّل',
    fix_en:'Turn on the append-only log to trace who changed what.',
    fix_ar:'فعّل سجل التدقيق لمعرفة من عدّل وماذا عدّل.' });

  return gaps;
}
